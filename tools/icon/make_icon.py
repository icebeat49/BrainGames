"""
Draws the BrainGames launcher icon from one geometry and writes every file that needs it:

- res/drawable/ic_launcher_background.xml, ic_launcher_foreground.xml, ic_launcher_monochrome.xml
  (adaptive icon layers, Android 8+; the monochrome layer is the themed icon of Android 13+)
- res/mipmap-*/ic_launcher.webp and ic_launcher_round.webp (Android 7, before adaptive icons)
- store/play_icon_512.png (Play Store listing)

The icon: a 3×3 grid of rounded tiles in the game colours (the Crowns region palette) on the
dark board colour, with a crown on the centre tile.

Run from the repository root:  python tools/icon/make_icon.py
Needs Pillow.
"""
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "app" / "src" / "main" / "res"

# Adaptive icon canvas: 108 dp, of which the launcher mask shows about the central 72 dp,
# and only a 66 dp circle is guaranteed. The 3×3 grid fits a square inside that circle.
CANVAS = 108.0
VISIBLE = 72.0
TILE = 14.0
GAP = 2.5
TILE_CORNER = 3.5
GRID = 3 * TILE + 2 * GAP
ORIGIN = (CANVAS - GRID) / 2

BOARD = "#141A26"
CROWN = "#231C3A"
# Row by row; the centre tile carries the crown.
TILE_COLOURS = [
    "#7FB2EE", "#DE6A5E", "#93BE84",
    "#9387E0", "#F0A63A", "#5DB5B1",
    "#D8BC3C", "#5584C8", "#E096B0",
]
CENTRE = 4

# The crown of the game (CrownVector.kt), on its 24-unit viewport, scaled onto the centre tile.
CROWN_SCALE = 0.54
CROWN_VIEWPORT_CENTRE = (12.0, 11.5)
CROWN_BODY = [(3, 8.5), (7.5, 12.5), (12, 5.5), (16.5, 12.5), (21, 8.5), (19, 17), (5, 17)]
CROWN_JEWELS = [(3, 6.2), (12, 3.6), (21, 6.2)]
CROWN_JEWEL_RADIUS = 2.0
CROWN_BAND = (5, 18.6, 19, 21.4)
CROWN_PATH = (
    "M3,8.5 L7.5,12.5 L12,5.5 L16.5,12.5 L21,8.5 L19,17 L5,17 Z "
    "M1,6.2 a2,2 0 1,0 4,0 a2,2 0 1,0 -4,0 Z "
    "M10,3.6 a2,2 0 1,0 4,0 a2,2 0 1,0 -4,0 Z "
    "M19,6.2 a2,2 0 1,0 4,0 a2,2 0 1,0 -4,0 Z "
    "M5,18.6 L19,18.6 L19,21.4 L5,21.4 Z"
)


def tile_origin(index):
    row, col = divmod(index, 3)
    return ORIGIN + col * (TILE + GAP), ORIGIN + row * (TILE + GAP)


def crown_offset():
    x, y = tile_origin(CENTRE)
    cx, cy = CROWN_VIEWPORT_CENTRE
    return x + TILE / 2 - cx * CROWN_SCALE, y + TILE / 2 - cy * CROWN_SCALE


def rounded_rect_path(x, y, w, h, r):
    return (
        f"M{x + r:g},{y:g} H{x + w - r:g} A{r:g},{r:g} 0 0 1 {x + w:g},{y + r:g} "
        f"V{y + h - r:g} A{r:g},{r:g} 0 0 1 {x + w - r:g},{y + h:g} "
        f"H{x + r:g} A{r:g},{r:g} 0 0 1 {x:g},{y + h - r:g} "
        f"V{y + r:g} A{r:g},{r:g} 0 0 1 {x + r:g},{y:g} Z"
    )


def vector(paths_xml):
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tools/icon/make_icon.py: edit the script, not this file. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp"\n'
        '    android:height="108dp"\n'
        f'    android:viewportWidth="{CANVAS:g}"\n'
        f'    android:viewportHeight="{CANVAS:g}">\n'
        f"{paths_xml}"
        "</vector>\n"
    )


def crown_group(colour):
    dx, dy = crown_offset()
    return (
        f'    <group android:translateX="{dx:g}" android:translateY="{dy:g}"\n'
        f'        android:scaleX="{CROWN_SCALE:g}" android:scaleY="{CROWN_SCALE:g}">\n'
        f'        <path android:fillColor="{colour}" android:pathData="{CROWN_PATH}" />\n'
        "    </group>\n"
    )


def write_vectors():
    drawable = RES / "drawable"
    background = f'    <path android:fillColor="{BOARD}" android:pathData="M0,0 H108 V108 H0 Z" />\n'
    tiles = "".join(
        f'    <path android:fillColor="{colour}" '
        f'android:pathData="{rounded_rect_path(*tile_origin(i), TILE, TILE, TILE_CORNER)}" />\n'
        for i, colour in enumerate(TILE_COLOURS)
    )
    # Monochrome: only the shapes count. The centre tile is left out so the crown reads on its own.
    mono_tiles = "".join(
        f'    <path android:fillColor="#FFFFFFFF" '
        f'android:pathData="{rounded_rect_path(*tile_origin(i), TILE, TILE, TILE_CORNER)}" />\n'
        for i in range(9) if i != CENTRE
    )
    (drawable / "ic_launcher_background.xml").write_text(vector(background), encoding="utf-8")
    (drawable / "ic_launcher_foreground.xml").write_text(vector(tiles + crown_group(CROWN)), encoding="utf-8")
    (drawable / "ic_launcher_monochrome.xml").write_text(
        vector(mono_tiles + crown_group("#FFFFFFFF")), encoding="utf-8"
    )


def render(size_px, region_dp, shape):
    """The icon at [size_px], showing the central [region_dp] of the canvas, masked to [shape]."""
    supersample = 4
    big = size_px * supersample
    scale = big / region_dp
    shift = (CANVAS - region_dp) / 2

    def px(v):
        return (v - shift) * scale

    image = Image.new("RGBA", (big, big), BOARD)
    draw = ImageDraw.Draw(image)
    for i, colour in enumerate(TILE_COLOURS):
        x, y = tile_origin(i)
        draw.rounded_rectangle(
            [px(x), px(y), px(x + TILE), px(y + TILE)], radius=TILE_CORNER * scale, fill=colour
        )
    dx, dy = crown_offset()

    def cp(point):
        return px(dx + point[0] * CROWN_SCALE), px(dy + point[1] * CROWN_SCALE)

    draw.polygon([cp(p) for p in CROWN_BODY], fill=CROWN)
    for jewel in CROWN_JEWELS:
        (cx, cy), r = cp(jewel), CROWN_JEWEL_RADIUS * CROWN_SCALE * scale
        draw.ellipse([cx - r, cy - r, cx + r, cy + r], fill=CROWN)
    x0, y0, x1, y1 = CROWN_BAND
    draw.rectangle([*cp((x0, y0)), *cp((x1, y1))], fill=CROWN)

    if shape != "square":
        mask = Image.new("L", (big, big), 0)
        mask_draw = ImageDraw.Draw(mask)
        if shape == "circle":
            mask_draw.ellipse([0, 0, big - 1, big - 1], fill=255)
        else:  # rounded square, like the legacy launcher icons
            mask_draw.rounded_rectangle([0, 0, big - 1, big - 1], radius=big * 0.18, fill=255)
        image.putalpha(mask)
    return image.resize((size_px, size_px), Image.LANCZOS)


LEGACY_SIZES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}


def write_rasters():
    for density, size in LEGACY_SIZES.items():
        folder = RES / f"mipmap-{density}"
        render(size, VISIBLE, "rounded").save(folder / "ic_launcher.webp", lossless=True)
        render(size, VISIBLE, "circle").save(folder / "ic_launcher_round.webp", lossless=True)
    store = ROOT / "store"
    store.mkdir(exist_ok=True)
    # Play applies its own rounded mask: a full square, showing the same area as the launcher.
    render(512, VISIBLE, "square").convert("RGB").save(store / "play_icon_512.png")


if __name__ == "__main__":
    write_vectors()
    write_rasters()
    print("Icon files written.")
