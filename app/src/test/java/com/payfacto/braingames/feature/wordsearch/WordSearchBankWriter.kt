package com.payfacto.braingames.feature.wordsearch

import com.payfacto.braingames.feature.wordsearch.data.SecretPicker
import com.payfacto.braingames.feature.wordsearch.data.WordSearchBankFormat
import com.payfacto.braingames.feature.wordsearch.data.WordSearchBankGenerator
import com.payfacto.braingames.feature.wordsearch.model.BankPuzzle
import org.junit.Ignore
import org.junit.Test
import kotlin.random.Random

/**
 * Regenerates the bundled banks (res/raw/wordsearch_bank_<lang>_<size>.txt) from the word lists
 * in src/test/resources/wordsearch. Every puzzle of a language gets its own secret, across both
 * sizes. Not part of the normal run: remove @Ignore, run this test alone, restore @Ignore.
 * WordSearchBankTest then re-verifies every puzzle written.
 */
class WordSearchBankWriter {

    @Ignore("Run manually to regenerate the bundled banks")
    @Test
    fun writeBanks() {
        val report = StringBuilder("\nWord Search bank generation\n")
        WordSearchBankFiles.LANGUAGES.forEachIndexed { languageIndex, language ->
            val usedSecrets = mutableSetOf<String>()
            WordSearchBankFiles.SIZES.forEach { size ->
                val seed = BANK_SEED + languageIndex * 100 + size
                val random = Random(seed)
                val secrets = UnusedSecrets(WordSearchBankFiles.secrets(language), WordSearchBankFiles.secretLengthsFor(size), usedSecrets, random)
                val start = System.nanoTime()
                val (puzzles, attempts) = generateBank(language, size, secrets, random)
                val seconds = (System.nanoTime() - start) / 1e9
                val header = "Word Search puzzle bank, $language, ${size}x$size, ${puzzles.size} verified puzzles.\n" +
                    "Generated by WordSearchBankWriter (seed $seed). One per line, space separated: the grid\n" +
                    "letters row by row, the secret ('_' between the words of a phrase), then the words to\n" +
                    "find. Each word appears exactly once; the letters no word covers spell the secret, read\n" +
                    "left to right, top to bottom. No secret is used twice in this language."
                WordSearchBankFiles.file(language, size).writeText(WordSearchBankFormat.write(puzzles, header))
                val words = puzzles.map { it.words.size }
                report.append(
                    "%s %dx%d: %d puzzles from %d attempts in %.1f s, %d-%d words, %d secrets left in range\n".format(
                        language, size, size, puzzles.size, attempts, seconds, words.min(), words.max(), secrets.leftCount(),
                    )
                )
            }
        }
        println(report)
    }

    private fun generateBank(language: String, size: Int, secrets: UnusedSecrets, random: Random): Pair<List<BankPuzzle>, Int> {
        val rules = WordSearchBankFiles.rules(language, size)
        val generator = WordSearchBankGenerator(random)
        val puzzles = LinkedHashMap<String, BankPuzzle>()
        var attempts = 0
        while (puzzles.size < PUZZLES_PER_BANK) {
            check(secrets.lengths().isNotEmpty()) { "$language ${size}x$size: out of secrets after ${puzzles.size} puzzles" }
            attempts++
            val puzzle = generator.generate(rules, secrets) ?: continue
            if (puzzles.putIfAbsent(puzzle.letters, puzzle) == null) secrets.markUsed(puzzle.secret)
        }
        return puzzles.values.toList() to attempts
    }

    /** Hands out secrets of the given letter counts that no accepted puzzle of the language uses yet. */
    private class UnusedSecrets(
        all: List<String>,
        lengths: IntRange,
        private val used: MutableSet<String>,
        private val random: Random,
    ) : SecretPicker {
        private val byLength = all.groupBy { BankPuzzle.secretLettersOf(it).length }.filterKeys { it in lengths }

        override fun lengths(): List<Int> = byLength.filterValues { list -> list.any { it !in used } }.keys.toList()

        override fun pick(length: Int): String? = byLength[length]?.filterNot { it in used }?.randomOrNull(random)

        fun markUsed(secret: String) {
            used += secret
        }

        fun leftCount(): Int = byLength.values.sumOf { list -> list.count { it !in used } }
    }

    private companion object {
        const val PUZZLES_PER_BANK = 100
        const val BANK_SEED = 8_200_000L
    }
}
