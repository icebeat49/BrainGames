package com.payfacto.braingames.feature.kakuro

import com.payfacto.braingames.core.model.Difficulty
import com.payfacto.braingames.feature.kakuro.data.KakuroBankFormat
import com.payfacto.braingames.feature.kakuro.engine.KakuroDifficulty
import com.payfacto.braingames.feature.kakuro.engine.KakuroGenerator
import com.payfacto.braingames.feature.kakuro.engine.KakuroPuzzle
import com.payfacto.braingames.feature.kakuro.engine.KakuroSolver
import org.junit.Ignore
import org.junit.Test
import kotlin.random.Random

/**
 * Regenerates the bundled bank (res/raw/kakuro_bank_<size>.txt). Not part of the normal run:
 * remove @Ignore, run this test alone (several minutes), restore @Ignore. KakuroBankTest then
 * re-verifies every puzzle written.
 */
class KakuroBankWriter {

    @Ignore("Run manually to regenerate the bundled bank")
    @Test
    fun writeBank() {
        val report = StringBuilder("\nKakuro bank generation\n")
        Difficulty.entries.forEach { difficulty ->
            val rules = KakuroDifficulty.rulesFor(difficulty)
            val seed = BANK_SEED + rules.size
            val generator = KakuroGenerator(Random(seed))
            val puzzles = LinkedHashSet<KakuroPuzzle>()
            var generated = 0
            val start = System.nanoTime()
            while (puzzles.size < PUZZLES_PER_SIZE) {
                val puzzle = generator.generate(rules) ?: continue
                generated++
                val grade = KakuroSolver.grade(puzzle.clues) ?: continue
                if (KakuroDifficulty.accepts(difficulty, grade)) puzzles += puzzle
            }
            val seconds = (System.nanoTime() - start) / 1e9
            val header = "Kakuro puzzle bank, ${rules.size}x${rules.size} ($difficulty), ${puzzles.size} verified puzzles.\n" +
                "Generated by KakuroBankWriter (seed $seed). One per line: the solution row by row,\n" +
                "'.' = block, digit = white cell. Clues are the sums of the solution runs."
            KakuroBankFiles.file(rules.size).writeText(KakuroBankFormat.write(puzzles, header))
            report.append(
                "%dx%d: %d puzzles kept of %d unique in %.1f s\n".format(rules.size, rules.size, puzzles.size, generated, seconds)
            )
        }
        println(report)
    }

    private companion object {
        const val PUZZLES_PER_SIZE = 250
        const val BANK_SEED = 7_100_000L
    }
}
